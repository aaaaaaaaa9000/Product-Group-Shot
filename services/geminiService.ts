import { GoogleGenAI, Modality, Part, GenerateContentResponse, HarmCategory, HarmBlockThreshold } from "@google/genai";
import { ImageFile } from '../types';

if (!process.env.API_KEY) {
  throw new Error("API_KEY environment variable not set");
}

const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

const DEFAULT_SAFETY_SETTINGS = [
  {
    category: HarmCategory.HARM_CATEGORY_HARASSMENT,
    threshold: HarmBlockThreshold.BLOCK_NONE,
  },
  {
    category: HarmCategory.HARM_CATEGORY_HATE_SPEECH,
    threshold: HarmBlockThreshold.BLOCK_NONE,
  },
  {
    category: HarmCategory.HARM_CATEGORY_SEXUALLY_EXPLICIT,
    threshold: HarmBlockThreshold.BLOCK_NONE,
  },
  {
    category: HarmCategory.HARM_CATEGORY_DANGEROUS_CONTENT,
    threshold: HarmBlockThreshold.BLOCK_NONE,
  },
];

export async function generateImage(
  productImage: ImageFile,
  prompt: string,
  styleImage: ImageFile | null
): Promise<ImageFile> {
  const model = 'gemini-2.5-flash-image';

  const parts: Part[] = [
    {
      inlineData: {
        data: productImage.base64,
        mimeType: productImage.mimeType,
      },
    },
    { text: prompt },
  ];

  if (styleImage) {
    parts.push({
      inlineData: {
        data: styleImage.base64,
        mimeType: styleImage.mimeType,
      },
    });
  }

  try {
    const response = await ai.models.generateContent({
      model: model,
      contents: { parts: parts },
      config: {
        responseModalities: [Modality.IMAGE],
        safetySettings: DEFAULT_SAFETY_SETTINGS
      },
    });

    for (const part of response.candidates?.[0]?.content?.parts || []) {
      if (part.inlineData) {
        return {
          base64: part.inlineData.data,
          mimeType: part.inlineData.mimeType,
          name: 'generated-image.jpg',
        };
      }
    }
    
    // Check for safety ratings or blocks if no image is returned
    const finishReason = response.candidates?.[0]?.finishReason;
    if (finishReason && finishReason !== 'STOP') {
        throw new Error(`Image generation failed due to safety settings: ${finishReason}`);
    }

    throw new Error('No image was generated by the model.');

  } catch (error) {
    console.error('Error calling Gemini API:', error);
    if (error instanceof Error && error.message.includes('safety settings')) {
        throw error;
    }
    throw new Error(error instanceof Error ? error.message : 'Failed to generate image. Please check your prompt or API key.');
  }
}

export async function analyzeStyleImage(styleImage: ImageFile): Promise<string> {
  const model = 'gemini-3-flash-preview';
  
  const imagePart = {
    inlineData: {
      data: styleImage.base64,
      mimeType: styleImage.mimeType,
    },
  };
  
  const textPart = {
    text: "Analyze this image and describe its aesthetic, color palette, and mood in a concise phrase suitable for a prompt. For example: 'A vibrant, high-contrast style with bold neon colors and a futuristic mood.'",
  };

  try {
    const response: GenerateContentResponse = await ai.models.generateContent({
      model: model,
      contents: { parts: [imagePart, textPart] },
      config: {
        safetySettings: DEFAULT_SAFETY_SETTINGS
      }
    });
    
    if(!response.text) {
      // Check for safety ratings or blocks if no text is returned
      const finishReason = response.candidates?.[0]?.finishReason;
      if (finishReason && finishReason !== 'STOP') {
          throw new Error(`Style analysis failed due to safety settings: ${finishReason}`);
      }
      throw new Error('Model returned no text for style analysis.');
    }
    
    return response.text.trim();

  } catch (error) {
    console.error('Error analyzing style image:', error);
    throw new Error('Failed to analyze style image.');
  }
}


export async function applyBackgroundBlur(
  sourceImage: ImageFile,
  blurIntensity: number
): Promise<ImageFile> {
  const model = 'gemini-2.5-flash-image';

  const prompt = `Keeping the main subject in sharp focus, apply a photographic gaussian blur effect to the background of this image. The blur intensity should be equivalent to a ${blurIntensity}px radius. Ensure a natural, soft fall-off (bokeh). Return only the modified image.`;

  const parts: Part[] = [
    {
      inlineData: {
        data: sourceImage.base64,
        mimeType: sourceImage.mimeType,
      },
    },
    { text: prompt },
  ];

  try {
    const response = await ai.models.generateContent({
      model: model,
      contents: { parts: parts },
      config: {
        responseModalities: [Modality.IMAGE],
        safetySettings: DEFAULT_SAFETY_SETTINGS
      },
    });

    for (const part of response.candidates?.[0]?.content?.parts || []) {
      if (part.inlineData) {
        return {
          base64: part.inlineData.data,
          mimeType: part.inlineData.mimeType,
          name: `blurred-${sourceImage.name || 'image'}.jpg`,
        };
      }
    }

    const finishReason = response.candidates?.[0]?.finishReason;
    if (finishReason && finishReason !== 'STOP') {
        throw new Error(`Image blurring failed due to safety settings: ${finishReason}`);
    }

    throw new Error('No blurred image was generated by the model.');

  } catch (error) {
    console.error('Error calling Gemini API for blur:', error);
    if (error instanceof Error && error.message.includes('safety settings')) {
        throw error;
    }
    throw new Error(error instanceof Error ? error.message : 'Failed to apply background blur. Please try again.');
  }
}